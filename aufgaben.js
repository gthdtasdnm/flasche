/** Der Stapel für eine Wahl in einem Modus. `null` heisst: kein Stapel noetig. */
export function stapelFuer(modus, wahl) {
  if (modus === "nurdrehen") return null;
  if (wahl === "wahrheit") {
    return modus === "frech"
      ? [...WAHRHEIT_HARMLOS, ...WAHRHEIT_FRECH]
      : WAHRHEIT_HARMLOS.slice();
  }
  return modus === "frech"
    ? [...PFLICHT_HARMLOS, ...PFLICHT_FRECH]
    : PFLICHT_HARMLOS.slice();
}
