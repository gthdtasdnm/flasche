//
// Alle Texte sind selbst geschrieben, aus keiner Anleitung und keiner App
// abgetippt. Regeln sind frei, fremde Kartentexte nicht.
//
// Zwei Stufen, beide **ohne Alkohol, ohne Sex und ohne Körperkontakt**:
//
//   HARMLOS  laesst sich am Familientisch vorlesen
//   FRECH    zielt auf Peinlichkeiten und Geständnisse, bleibt jugendfrei
//
// Warum kein 18+-Stapel wie in „Ich hab noch nie": SPIELE-IDEEN.md verlangt
// für alles aus der Trinkspiel-Sparte einen eigenen Bereich mit
// Volljährigkeitshinweis, „trinkfrei" als Voreinstellung und eine
// Jugendschutz-Abwaegung. Dieses Spiel umgeht das, indem es gar nicht erst
// dorthin geht – dieselbe Entscheidung wie bei „Wer am ehesten". Wer den
// Stapel spaeter erweitert, holt sich die ganze Abwaegung mit dazu.
//
// Zwei Regeln fuer jede Pflicht, die probe.js nicht pruefen kann und die
// deshalb hier stehen: sie muss **im Sitzen am Tisch** erfuellbar sein, und
// sie darf **niemanden anfassen** und niemanden blossstellen, der nicht
// mitspielt.

